#!/usr/bin/env python3
"""X1: build the comparison table from the raw results.

Usage, from experiments/X1:  python3 -I -X utf8 scripts/summarize.py
Reads results/*.json and results/rust/*.jsonl; writes results/message-table.md.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent.parent
R = HERE / "results"


def main():
    py = json.loads((R / "python.json").read_text())["messages"]
    ccc = json.loads((R / "ccc.json").read_text())["messages"]
    neu = json.loads((R / "neuron.json").read_text())["cases"]
    rust = {}
    for f in (R / "rust").glob("*.jsonl"):
        for line in f.read_text().splitlines():
            d = json.loads(line)
            msg = d.get("message")
            if msg is None and "message 0x" in d.get("error", ""):
                msg = d["error"].split("message ")[1].split(" ")[0] + " (then refused to sign)"
            rust[(f.stem, d["group"], d["path"])] = msg or ("error: " + d.get("error", "")[:60])
    verify = json.loads((R / "verify.json").read_text())
    runs = json.loads((R / "assembly.json").read_text())["runs"]
    asm = {r["case"]: r for r in runs if r.get("committed_block")}
    neg = {r["case"]: r for r in runs if r["kind"] == "negative"}

    def mark(m, ref):
        if m is None:
            return "-"
        if m.startswith("error"):
            return m
        base = m.split(" ")[0]
        tail = m[len(base):]
        return ("same" if base == ref else f"**DIFFERENT** `{base[:12]}…`") + tail

    rows = ["| Case | Lock group | Message (implementation M, Python) | CCC 1.23.1 | ckb-cli 2.0.0 build_signature | ckb-sdk 5.0.0 signer | Neuron 0.204.1 | Devnet |",
            "|---|---|---|---|---|---|---|---|"]
    for cid in sorted(py):
        for g, m in py[cid].items():
            n = neu.get(cid, {}).get("groups", {}).get(g)
            nm = n["direct_message"] if n else None
            if n and not n.get("neuron_recognises_lock"):
                note = n.get("neuron_config_error") or "lock not recognised by Neuron's config"
                nm = (nm + f" (message function only; {note})") if nm else None
            dev = asm.get(cid)
            if dev:
                dev = f"block {dev['committed_block']}"
            elif cid in neg:
                code = neg[cid]["error"].split("error code ")[1].split(" ")[0] if "error code " in neg[cid]["error"] else "?"
                dev = f"negative control: {'accepted' if neg[cid]['accepted'] else 'rejected'} (error {code})"
            else:
                dev = "mainnet (committed)" if cid.startswith("R") else "-"
            rows.append(f"| {cid} | {g} | `{m}` | {mark(ccc.get(cid, {}).get(g), m)} | "
                        f"{mark(rust.get((cid, g, 'ckb-cli v2.0.0 build_signature')), m)} | "
                        f"{mark(rust.get((cid, g, 'ckb-sdk 5.0.0 ScriptSigner::sign_tx')), m)} | "
                        f"{mark(nm, m) if n else 'not a multisig group'} | {dev} |")
    total = sum(len(ts) for gs in verify.values() for ks in gs.values() for ts in ks.values())
    bad = [f"{cid}/{g}/{k}/{t}" for cid, gs in verify.items() for g, ks in gs.items() for k, ts in ks.items()
           for t, v in ts.items() if not v["valid_for_M_message"]]
    text = ["# X1 message table (generated by scripts/summarize.py)", "",
            "\"same\" means byte for byte equal to the message from implementation M.", ""] + rows + [
        "", f"Signatures checked against implementation M's message: {total}; not valid: {', '.join(bad) or 'none'}.", ""]
    (R / "message-table.md").write_text("\n".join(text))
    print("\n".join(text))


if __name__ == "__main__":
    main()
